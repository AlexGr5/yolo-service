"""
Настройки сервиса.

Всё собрано в одном месте. Значения можно переопределить через переменные
окружения — удобно и локально, и в Docker (через docker run -e MODEL_PATH=...).
Так не приходится пересобирать образ из-за одной поменявшейся цифры.
"""
import os


# Путь к файлу весов модели. По умолчанию относительный путь models/yolov8n.pt.
# Важно, что не используем локальные абсолютные пути вида C:/... или /home/user/...
# Это универсальный вариант — такой проект запустится
# везде, а не только на локальной машине.
# Если файла по этому пути нет, ultralytics сам скачает веса по имени yolov8n.pt
# и положит их в кэш или в текущую директорию.
MODEL_PATH = os.getenv("MODEL_PATH", "models/yolov8n.pt")

# Входной размер модели. YOLOv8n обучена на 640 на 640 пикселей. Менять
# не рекомендуется. Модель видела объекты именно в этом разрешении, на другом
# начнёт ошибаться.
MODEL_INPUT_SIZE = 640

# Максимальный размер загружаемого изображения — десять мегабайт.
# При превышении возвращаем HTTP 413. Без него один злой
# пользователь закинет гигабайтную картинку и займёт всю память сервиса.
MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024

# Цвет педдинга при letterbox. 114 — серый, это стандарт из репозитория
# ultralytics. Именно серый безопаснее всего: модель на обучении видела
# такие же серые полосы и привыкла их игнорировать. Чёрный модель могла бы
# принять за тень, белый за светлый объект.
PADDING_COLOR = 114

# Порог уверенности по умолчанию. Детекции со score меньше этого значения
# отбрасываются. 0.25 — стандарт из ultralytics. Ниже — много ложных
# срабатываний, выше — пропуск реальных объектов с плохой видимостью.
DEFAULT_CONF_THRESHOLD = 0.25

# Порог IoU для NMS по умолчанию. Пары рамок с IoU больше этого значения
# считаются дубликатами, менее уверенная подавляется. 0.45 — компромисс
# между слишком агрессивным подавлением соседних объектов и оставшимися
# дубликатами на один объект.
DEFAULT_IOU_THRESHOLD = 0.45