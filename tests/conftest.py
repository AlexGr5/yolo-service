"""
Общие заготовки для всех тестов.

Тут собрано то, что нужно сразу нескольким файлам. Например тестовая картинка
пригодится и в тестах на API, и в тестах на ошибки. Создавать её заново в каждом
файле — лишняя писанина. Один раз положили здесь — все тесты берут отсюда.
"""
import sys
from pathlib import Path

# Pytest стартует из корня проекта, но пакет app по умолчанию не находится,
# потому что корень проекта не в путях поиска модулей. Добавляем руками,
# иначе import app ниже упадёт с ModuleNotFoundError. Делаем это строго
# до остальных импортов.
project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

import io
import pytest
from PIL import Image


@pytest.fixture
def sample_image_bytes():
    # Обычная валидная картинка 640 на 480 с красным фоном. Размер специально
    # не квадратный. На квадратной картинке letterbox ничего не делает, и
    # проверить его было бы не на чем. А на прямоугольной он реально работает.
    #
    # Возвращаем байты PNG, потому что именно байты ждёт UploadFile в эндпоинте.
    image = Image.new("RGB", (640, 480), color=(255, 0, 0))
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    # После save курсор буфера стоит в конце. Чтобы getvalue вернул всё
    # содержимое с начала, перематываем.
    buffer.seek(0)
    return buffer.getvalue()


@pytest.fixture
def empty_bytes():
    # Ноль байт. Используется в тесте на пустой файл: сервис должен ответить
    # 400 с понятным сообщением, а не упасть с 500.
    return b""


@pytest.fixture
def not_an_image_bytes():
    # Валидный текст, но не картинка. Pillow на этом упадёт при декодировании,
    # и сервис должен превратить это в 400, а не в 500.
    return b"this is not an image, just some text bytes"


@pytest.fixture
def huge_bytes():
    # Одиннадцать мегабайт нулей. Лимит в проекте десять мегабайт, а тут с запасом,
    # чтобы проверка размера гарантированно сработала. Умножение байтовой строки
    # на число создаёт данные прямо в памяти и не трогает диск.
    return b"0" * (11 * 1024 * 1024)